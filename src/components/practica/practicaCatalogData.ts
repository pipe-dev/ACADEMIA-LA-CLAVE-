// ─── Top Equilibrado Combinado (Para la pestaña "Todos") ───
export const RECOMMENDED_TRACKS: CatalogTrack[] = (() => {
  const combined: CatalogTrack[] = [];
  const sMax = DEFAULT_SECULAR_TRACKS.length;
  const cMax = DEFAULT_CHRISTIAN_TRACKS.length;
  let s = 0;
  let c = 0;

  while (s < sMax || c < cMax) {
    // Intercalar: 2 seculares por 1 cristiana
    for (let i = 0; i < 2 && s < sMax; i++) {
      const track = DEFAULT_SECULAR_TRACKS[s++];
      const rank = combined.length + 1;
      combined.push({ ...track, id: `rec_${rank}`, rank });
    }
    if (c < cMax) {
      const track = DEFAULT_CHRISTIAN_TRACKS[c++];
      const rank = combined.length + 1;
      combined.push({ ...track, id: `rec_${rank}`, rank });
    }
  }

  return combined;
})();

